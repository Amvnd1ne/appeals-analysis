USER_NAMES = [
    "Иван Петров", "Мария Смирнова", "Алексей Кузнецов", "Ольга Попова",
    "Дмитрий Соколов", "Анна Лебедева", "Сергей Козлов", "Екатерина Новикова",
    "Павел Морозов", "Татьяна Волкова", "Никита Зайцев", "Юлия Павлова",
]

STATUSES = ["new", "in_progress", "resolved", "closed"]


def seed():
    conn = get_connection()
    cur = conn.cursor()

    cur.execute("SELECT COUNT(*) AS cnt FROM appeals")
    existing = cur.fetchone()["cnt"]
    if existing > 0:
        print(f"В БД уже есть {existing} обращений. Дополнительно добавим 80.")

    cur.execute("SELECT name FROM categories")
    categories = [row["name"] for row in cur.fetchall()]

    now = datetime.now()
    inserted = 0

    for _ in range(80):
        category = random.choice(categories)
        text = random.choice(SAMPLES[category])
        user_name = random.choice(USER_NAMES)
        status = random.choice(STATUSES)

        # Случайная дата в пределах последних 90 дней
        days_ago = random.randint(0, 90)
        hours_ago = random.randint(0, 23)
        created_at = (now - timedelta(days=days_ago, hours=hours_ago)).strftime(
            "%Y-%m-%d %H:%M:%S"
        )

        cur.execute(
            """INSERT INTO appeals (created_at, text, category, user_name, status)
               VALUES (?, ?, ?, ?, ?)""",
            (created_at, text, category, user_name, status),
        )
        inserted += 1

    conn.commit()

    cur.execute("SELECT COUNT(*) AS cnt FROM appeals")
    total = cur.fetchone()["cnt"]
    conn.close()

    print(f"Добавлено {inserted} обращений. Всего в БД {total}.")


if __name__ == "__main__":
    seed()
